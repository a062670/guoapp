  /// 单个字符的拼音首字母；非汉字返回 null。
  static String? initialOf(int rune) {
    final index = rune - 0x4E00;
    if (index < 0 || index >= _initials.length) return null;
    final letter = _initials[index];
    return letter == '.' ? null : letter;
  }

  /// 名称 -> 排序键：汉字取拼音首字母，英数字大写化，其余字符原样。
  /// 「爱情」-> AI、「动作」-> DZ、「短剧」-> DJ、「Action」-> ACTION。
  static String sortKey(String name) {
    final buffer = StringBuffer();
    for (final rune in name.runes) {
      buffer.write(initialOf(rune) ?? String.fromCharCode(rune).toUpperCase());
    }
    return buffer.toString();
  }
